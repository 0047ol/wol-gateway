  function translate(value, language) {
    const source = String(value ?? '');
    if (language !== 'en') return source;
    const text = source.trim();
    let result = en[text];
    if (result === undefined) {
      for (const [pattern, replace] of patterns) {
        if (pattern.test(text)) {
          result = text.replace(pattern, replace);
          break;
        }
      }
    }
    if (result === undefined) {
      for (const [prefix, translated] of Object.entries(prefixes)) {
        if (text.startsWith(prefix)) {
          result = translated + translate(text.slice(prefix.length), language);
          break;
        }
      }
    }
    if (result === undefined && text.includes('\n')) result = text.split('\n').map(line => translate(line, language)).join('\n');
    if (result === undefined && text.includes('；') && text.split('；').every(part => !/[\u4e00-\u9fff]/.test(translate(part, language)))) result = text.split('；').map(part => translate(part, language)).join('; ');
    return result === undefined ? source : source.replace(text, () => result);
  }
